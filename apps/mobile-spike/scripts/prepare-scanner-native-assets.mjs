#!/usr/bin/env node
/**
 * Stages the pinned DINOv2 model and the committed visual index into
 * apps/mobile-spike/assets/scanner/ so Metro can bundle them (require()'d, assetExts: onnx/bin —
 * see metro.config.js). Mirrors the web app's own scripts/prepare-scanner-visual-assets.mjs split
 * exactly: the INDEX is copied from the repo's one committed, versioned generation
 * (scripts/scanner-visual-index/generated/, the .gitignore's own D-097 exception — never
 * regenerated here), the MODEL is downloaded fresh from the pinned Hugging Face revision and
 * verified by SHA-256 before anything is staged (never trusted from a mutable "latest").
 *
 * Both outputs land under apps/mobile-spike/assets/scanner/, which is entirely gitignored (see
 * .gitignore's "Scanner artefacts" section) — regenerated by this script, never committed, exactly
 * like /public/scanner-assets/ for the web build.
 */
import { createHash } from 'node:crypto'
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  VISUAL_MODEL_FILES,
  VISUAL_MODEL_REPO,
  VISUAL_MODEL_REVISION,
} from '../../../scripts/scanner-visual-index/lib/model-pin.mjs'

const appRoot = join(dirname(fileURLToPath(import.meta.url)), '..')
const repoRoot = join(appRoot, '..', '..')
const outRoot = join(appRoot, 'assets', 'scanner', 'visual-v1')
const generatedRoot = join(repoRoot, 'scripts', 'scanner-visual-index', 'generated', 'visual-v1')

function sha256(path) {
  return createHash('sha256').update(readFileSync(path)).digest('hex')
}

function stageIndex() {
  // The current generation is resolved from the repo's own committed pointer file
  // (generated/visual-v1/current.json — the same bootstrap pointer the web build reads), never
  // hardcoded, so this script always stages whatever generation the repo's own data says is current.
  const pointer = JSON.parse(readFileSync(join(generatedRoot, 'current.json'), 'utf-8'))
  const generationDir = join(generatedRoot, 'generations', pointer.contentId)
  const outDir = join(outRoot, 'index')
  mkdirSync(outDir, { recursive: true })
  for (const name of ['manifest.json', 'card-ids.json', 'embeddings.bin']) {
    copyFileSync(join(generationDir, name), join(outDir, name))
  }
  const manifest = JSON.parse(readFileSync(join(outDir, 'manifest.json'), 'utf-8'))
  const actualEmbeddingsSha = sha256(join(outDir, 'embeddings.bin'))
  if (actualEmbeddingsSha !== manifest.embeddingsSha256) {
    throw new Error(
      `prepare-scanner-native-assets: embeddings.bin hash mismatch (expected ${manifest.embeddingsSha256}, got ${actualEmbeddingsSha})`,
    )
  }
  console.log(`Staged visual index ${pointer.contentId} (${manifest.cardCount} cards).`)
  return manifest
}

async function stageModel(expectedModelSha256) {
  const outDir = join(outRoot, 'model')
  mkdirSync(join(outDir, 'onnx'), { recursive: true })
  for (const file of VISUAL_MODEL_FILES) {
    const dest = join(outDir, file.stagedName)
    mkdirSync(dirname(dest), { recursive: true })
    if (existsSync(dest) && sha256(dest) === file.sha256) continue
    const url = `https://huggingface.co/${VISUAL_MODEL_REPO}/resolve/${VISUAL_MODEL_REVISION}/${file.upstreamPath}`
    const response = await fetch(url)
    if (!response.ok) {
      throw new Error(`prepare-scanner-native-assets: fetch failed for ${url}: HTTP ${response.status}`)
    }
    const bytes = new Uint8Array(await response.arrayBuffer())
    writeFileSync(dest, bytes)
    const actualSha = sha256(dest)
    if (actualSha !== file.sha256) {
      throw new Error(
        `prepare-scanner-native-assets: ${file.stagedName} hash mismatch (expected ${file.sha256}, got ${actualSha})`,
      )
    }
  }
  const modelSha = sha256(join(outDir, 'onnx', 'model_quantized.onnx'))
  if (modelSha !== expectedModelSha256) {
    throw new Error(
      `prepare-scanner-native-assets: staged model hash (${modelSha}) does not match the index manifest's own modelSha256 (${expectedModelSha256}) — model/index revision mismatch.`,
    )
  }
  console.log(`Staged visual model ${VISUAL_MODEL_REPO}@${VISUAL_MODEL_REVISION}.`)
}

const manifest = stageIndex()
await stageModel(manifest.modelSha256)
console.log('Scanner assets ready.')
