/**
 * Expo config plugin: allow plain HTTP ONLY to the developer machine, for the local Supabase stack.
 *
 * Android blocks cleartext traffic by default (targetSdk >= 28). The Expo template re-enables it for
 * the debug build types only, so a RELEASE build (Hermes bytecode, embedded bundle: the build used
 * for runtime evidence) cannot reach `http://10.0.2.2:55321` and the app shows "Could not reach the
 * server" (observed in P166). Instead of the global `usesCleartextTraffic="true"`, this writes a
 * network security config that permits cleartext to exactly the loopback aliases the local-only
 * backend guard (src/config/backend-config.ts) already requires, and nothing else. Any other host
 * keeps the platform default (HTTPS only), and the app refuses non-local backends at startup anyway.
 *
 * SPIKE_ONLY: a product build talks HTTPS to a hosted backend and must drop this plugin.
 */
const { AndroidConfig, withAndroidManifest, withDangerousMod } = require('expo/config-plugins')
const fs = require('node:fs')
const path = require('node:path')

const LOCAL_HOSTS = ['10.0.2.2', '10.0.3.2', '127.0.0.1', 'localhost']

function networkSecurityConfigXml() {
  const domains = LOCAL_HOSTS.map(
    (h) => `    <domain includeSubdomains="false">${h}</domain>`,
  ).join('\n')
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-local-cleartext.js (P166 spike). Cleartext to local hosts only. -->
<network-security-config>
  <base-config cleartextTrafficPermitted="false" />
  <domain-config cleartextTrafficPermitted="true">
${domains}
  </domain-config>
</network-security-config>
`
}

function withLocalCleartext(config) {
  config = withDangerousMod(config, [
    'android',
    (cfg) => {
      const dir = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res', 'xml')
      fs.mkdirSync(dir, { recursive: true })
      fs.writeFileSync(path.join(dir, 'network_security_config.xml'), networkSecurityConfigXml())
      return cfg
    },
  ])
  return withAndroidManifest(config, (cfg) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults)
    app.$['android:networkSecurityConfig'] = '@xml/network_security_config'
    return cfg
  })
}

module.exports = withLocalCleartext
module.exports.LOCAL_HOSTS = LOCAL_HOSTS
module.exports.networkSecurityConfigXml = networkSecurityConfigXml
