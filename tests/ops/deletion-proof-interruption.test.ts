/**
 * P206: what happens when the owner-operated deletion proof is cancelled.
 *
 * The three cases the operator must be able to tell apart: cancelled BEFORE the delete request was
 * sent (nothing changed, safe to start again), the request SENT with no answer (outcome unknown -
 * never retry), and the answer received before the interruption. Everything here is mocked or runs
 * against a stand-in process: there is no Supabase project, no registry append or deletion, no
 * backup, and the stand-in's `fetch` is a tripwire that fails the test if an interruption touches
 * the network. Real signals are delivered to a real process (tests/ops/fixtures/interruption-child.ts,
 * which installs the SAME handler and summary builder as the tool).
 *
 * Platform limits, stated rather than papered over:
 *  - POSIX: SIGINT, SIGTERM and SIGHUP are delivered with kill(2) and all three are tested.
 *  - Windows: Node cannot send SIGINT to a child and `kill('SIGTERM')` terminates without a handler,
 *    so those cannot be observed. The real Ctrl+C and Ctrl+Break console events are generated by
 *    tests/ops/fixtures/send-console-event.ps1 against a child that launch-in-new-console.ps1 gave
 *    its own hidden console (Node's `detached` means no console at all on Windows).
 *    Ctrl+C is undeliverable to a process tree that was started with Ctrl+C disabled; the test then
 *    SKIPS with that reason instead of passing. SIGHUP (console window closed) has no safe way to be
 *    generated from a test and is covered only at the unit level.
 */

const repoRoot = fileURLToPath(new URL('../../', import.meta.url))
const FIXTURE = join(repoRoot, 'tests/ops/fixtures/interruption-child.ts')
const SENDER = join(repoRoot, 'tests/ops/fixtures/send-console-event.ps1')
const LAUNCHER = join(repoRoot, 'tests/ops/fixtures/launch-in-new-console.ps1')
const isWindows = process.platform === 'win32'

// Canary values, assembled at run time so no secret-shaped literal sits in the repository (the CI
// secret scan reads every commit). They only need to be distinctive enough to grep for in output.
const canary = (name: string): string => ['canary', name, 'ZXQJ7781'].join('-')
const SECRETS = {
  ERASURE_OPERATOR_TOKEN: canary('operator'),
  ERASURE_REGISTRY_KEY: canary('registry'),
  PP_SUPABASE_PUBLISHABLE_KEY: canary('publishable'),
}

const PHASES = {
  'before-send': {
    says: 'CANCELLED BEFORE THE DELETION REQUEST WAS SENT',
    forbids: [/DO NOT RUN/, /OUTCOME IS UNKNOWN/],
    sent: false,
    deleted: false,
  },
  'outcome-unknown': {
    says: 'THE OUTCOME IS UNKNOWN',
    forbids: [/safe to start the tool again/, /nothing was changed/i],
    sent: true,
    deleted: false,
  },
  'after-answer': {
    says: 'ANSWERED AS DELETED',
    forbids: [/safe to start the tool again/, /nothing was changed/i],
    sent: true,
    deleted: true,
  },
} as const
type Phase = keyof typeof PHASES

