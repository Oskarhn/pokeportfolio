describe('interruption handler (no process, no signals)', () => {
  const answer = { requestSent: true, requestAnswered: true, deleted: false }

  function harness(facts: () => InterruptionFacts, persistThrows = false) {
    const stderr: string[] = []
    const persisted: unknown[] = []
    const exits: number[] = []
    const handler = createInterruptionHandler({
      facts,
      writeStderr: (text) => stderr.push(text),
      persist: (report) => {
        if (persistThrows) throw new Error('disk full')
        persisted.push(report.phase)
      },
      exit: (code) => {
        exits.push(code)
        throw new Error('exit') // stands in for process.exit, which never returns
      },
    })
    const fire = (): void => {
      try {
        handler()
      } catch (error) {
        if ((error as Error).message !== 'exit') throw error
      }
    }
    return { fire, stderr, persisted, exits }
  }

  afterEach(() => {
    vi.unstubAllGlobals()
  })

  it.each(Object.keys(PHASES) as Phase[])(
    '%s: one message, one summary, one exit (130)',
    (phase) => {
      const facts: InterruptionFacts =
        phase === 'before-send'
          ? { requestSent: false, requestAnswered: false, deleted: false }
          : phase === 'outcome-unknown'
            ? { requestSent: true, requestAnswered: false, deleted: false }
            : { requestSent: true, requestAnswered: true, deleted: true }
      const h = harness(() => facts)
      h.fire()
      expect(h.exits).toEqual([130])
      expect(h.persisted).toEqual([phase])
      expect(h.stderr).toHaveLength(1)
      expect(h.stderr[0]).toContain(PHASES[phase].says)
      for (const forbidden of PHASES[phase].forbids) expect(h.stderr[0]).not.toMatch(forbidden)
    },
  )

  it('is idempotent: a second signal exits at once and writes nothing twice', () => {
    const h = harness(() => answer)
    h.fire()
    h.fire()
    h.fire()
    expect(h.exits).toEqual([130, 130, 130])
    expect(h.stderr).toHaveLength(1)
    expect(h.persisted).toHaveLength(1)
  })

  it('reads the facts when the signal arrives, not when the handler was created', () => {
    const facts: InterruptionFacts = { requestSent: false, requestAnswered: false, deleted: false }
    const h = harness(() => facts)
    facts.requestSent = true // the request left after the handler was installed
    h.fire()
    expect(h.stderr[0]).toContain('THE OUTCOME IS UNKNOWN')
  })

  it('still exits, with the message already written, when the summary cannot be saved', () => {
    const h = harness(() => answer, true)
    h.fire()
    expect(h.exits).toEqual([130])
    expect(h.stderr).toHaveLength(1)
  })

  it('never touches the network, whatever the phase', () => {
    const fetchSpy = vi.fn()
    vi.stubGlobal('fetch', fetchSpy)
    for (const facts of [
      { requestSent: false, requestAnswered: false, deleted: false },
      { requestSent: true, requestAnswered: false, deleted: false },
      answer,
    ]) {
      harness(() => facts).fire()
    }
    expect(fetchSpy).not.toHaveBeenCalled()
  })

  it('registers exactly SIGINT, SIGTERM, SIGHUP and SIGBREAK, all on the one handler', () => {
    const registered = new Map<string, unknown>()
    const fake = {
      on(signal: string, listener: unknown) {
        registered.set(signal, listener)
        return this
      },
    }
    const handler = (): never => {
      throw new Error('unused')
    }
    installInterruptionHandlers(handler, fake as unknown as Pick<NodeJS.Process, 'on'>)
    expect([...registered.keys()].sort()).toEqual(['SIGBREAK', 'SIGHUP', 'SIGINT', 'SIGTERM'])
    expect(new Set(registered.values())).toEqual(new Set([handler]))
    expect([...INTERRUPT_SIGNALS].sort()).toEqual(['SIGBREAK', 'SIGHUP', 'SIGINT', 'SIGTERM'])
  })

  it('the summary is a fixed set of fields: no id, token, address or response content', () => {
    const report = { phase: 'outcome-unknown' as const, exitCode: 130, lines: [] as string[] }
    const summary = interruptionSummary(
      { requestSent: true, requestAnswered: false, deleted: false },
      report,
      [{ gate: 'a gate', pass: true }],
    )
    expect(Object.keys(summary).sort()).toEqual([
      'deleted',
      'deletionRequestSent',
      'interrupted',
      'results',
      'stopped',
    ])
  })
})

describe('the tool routes every interruption path through the shared handler', () => {
  const source = readFileSync(
    join(repoRoot, 'scripts/restore-gate/owner-deletion-proof.ts'),
    'utf8',
  )
  const module = readFileSync(join(repoRoot, 'scripts/restore-gate/interruption.ts'), 'utf8')

  it('installs the handler for every signal and uses it for the raw-mode Ctrl+C byte', () => {
    expect(source).toContain('createInterruptionHandler')
    expect(source).toContain('installInterruptionHandlers(handleInterruption)')
    expect(source).toMatch(/ch === '\\u0003'[\s\S]{0,120}handleInterruption\(\)/)
    expect(source).toContain('interruptionSummary(state, report, results)')
  })

  it('has no bare exit left that would be a silent path', () => {
    expect(source).not.toMatch(/process\.exit\(130\)/)
    expect(source.match(/process\.exit\(/g)).toHaveLength(1) // only the handler's own exit
  })

  it('the shared module is the only place a report is built, and has no network or registry access', () => {
    expect(module).toContain('describeInterruption')
    expect(module).not.toMatch(/fetch\(|createClient|exportRegistry|RegistryStore|appendFile/)
  })
})

