interface Child {
  pid: number
  outDir: string
  stdout: () => string
  stderr: () => string
  ready: () => Promise<void>
  /** Resolves with the status the fixture exited with, or rejects when it is still alive at `ms`. */
  exited: (ms: number) => Promise<number>
  /** True once the process is gone (Windows tests: the only portable liveness check). */
  kill: () => void
}

const dirs: string[] = []
const killers: (() => void)[] = []

afterEach(() => {
  for (const kill of killers.splice(0)) kill()
  for (const dir of dirs.splice(0)) rmSync(dir, { recursive: true, force: true })
})

const sleep = (ms: number): Promise<void> => new Promise((resolve) => setTimeout(resolve, ms))

function alive(pid: number): boolean {
  try {
    process.kill(pid, 0)
    return true
  } catch {
    return false
  }
}

async function until(condition: () => boolean, ms: number, what: string): Promise<void> {
  const deadline = Date.now() + ms
  while (!condition()) {
    if (Date.now() > deadline) throw new Error(`${what} did not happen within ${String(ms)} ms`)
    await sleep(50)
  }
}

/** POSIX: a plain child process with pipes. */
function startPosix(phase: Phase): Child {
  const outDir = mkdtempSync(join(tmpdir(), 'p206-interrupt-'))
  dirs.push(outDir)
  const proc: ChildProcess = spawn(process.execPath, ['--import', 'tsx', FIXTURE, phase, outDir], {
    cwd: repoRoot,
    env: { ...process.env, ...SECRETS },
    stdio: ['ignore', 'pipe', 'pipe'],
  })
  let out = ''
  let err = ''
  let status: number | null = null
  proc.stdout?.on('data', (d: Buffer) => (out += d.toString('utf8')))
  proc.stderr?.on('data', (d: Buffer) => (err += d.toString('utf8')))
  proc.on('exit', (code) => {
    status = code ?? -1
  })
  const kill = (): void => {
    if (status === null) proc.kill('SIGKILL')
  }
  killers.push(kill)
  return {
    pid: proc.pid as number,
    outDir,
    stdout: () => out,
    stderr: () => err,
    ready: () => until(() => out.includes('READY'), 60_000, 'the fixture becoming ready'),
    exited: async (ms) => {
      await until(() => status !== null, ms, 'the exit after the signal')
      return status as unknown as number
    },
    kill,
  }
}

/** Windows: the fixture runs in its own hidden console so a console control event can reach it. */
async function startWindows(phase: Phase): Promise<Child> {
  const outDir = mkdtempSync(join(tmpdir(), 'p206-interrupt-'))
  dirs.push(outDir)
  // stdio is not piped: the console child inherits the launcher's handles, and a pipe it holds open
  // would keep a synchronous spawn waiting until its timeout. The PID comes back through a file.
  const launcher = spawn(
    'powershell.exe',
    [
      '-NoProfile',
      '-ExecutionPolicy',
      'Bypass',
      '-File',
      LAUNCHER,
      '-Node',
      process.execPath,
      '-Fixture',
      FIXTURE,
      '-Phase',
      phase,
      '-OutDir',
      outDir,
      '-WorkDir',
      repoRoot,
    ],
    { env: { ...process.env, ...SECRETS }, windowsHide: true, stdio: 'ignore' },
  )
  killers.push(() => {
    if (launcher.exitCode === null) launcher.kill()
  })
  const pidFile = join(outDir, 'pid.txt')
  await until(() => existsSync(pidFile), 60_000, 'the launcher reporting the fixture PID')
  await sleep(100)
  const pid = Number(readFileSync(pidFile, 'utf8').trim())
  if (!Number.isInteger(pid) || pid <= 0) throw new Error('the launcher wrote no usable PID')
  const read = (name: string): string => {
    try {
      return readFileSync(join(outDir, name), 'utf8')
    } catch {
      return ''
    }
  }
  const kill = (): void => {
    if (alive(pid)) spawnSync('taskkill', ['/PID', String(pid), '/F'], { windowsHide: true })
  }
  killers.push(kill)
  return {
    pid,
    outDir,
    stdout: () => read('child.stdout.txt'),
    stderr: () => read('child.stderr.txt'),
    ready: () =>
      until(() => read('child.stdout.txt').includes('READY'), 60_000, 'the fixture becoming ready'),
    exited: async (ms) => {
      await until(() => !alive(pid), ms, 'the process ending after the console event')
      // The handler records the status it exits with just before process.exit.
      await until(() => read('exit-code.txt') !== '', 5_000, 'the exit status being recorded')
      return Number(read('exit-code.txt'))
    },
    kill,
  }
}

function assertInterrupted(child: Child, phase: Phase, exitCode: number): void {
  const expected = PHASES[phase]
  // Exit status: 128 + SIGINT, for every phase and every signal, so a wrapper can tell it from a failure.
  expect(exitCode).toBe(130)

  const stderr = child.stderr()
  expect(stderr).toContain(expected.says)
  for (const forbidden of expected.forbids) expect(stderr).not.toMatch(forbidden)
  expect(child.stdout().replace('READY', '').trim()).toBe('')

  const summaryText = readFileSync(join(child.outDir, 'p197b-result.json'), 'utf8')
  const summary = JSON.parse(summaryText) as Record<string, unknown>
  expect(Object.keys(summary).sort()).toEqual([
    'deleted',
    'deletionRequestSent',
    'interrupted',
    'results',
    'stopped',
  ])
  expect(summary).toMatchObject({
    stopped: true,
    interrupted: phase,
    deletionRequestSent: expected.sent,
    deleted: expected.deleted,
  })

  // No request and no retry: the stand-in's fetch tripwire was never hit.
  expect(existsSync(join(child.outDir, 'NETWORK_USED'))).toBe(false)
  // No registry append or deletion: the file the stand-in created is byte-identical.
  const registry = readFileSync(join(child.outDir, 'registry.ndjson'))
  expect(createHash('sha256').update(registry).digest('hex')).toBe(
    readFileSync(join(child.outDir, 'registry.sha256'), 'utf8'),
  )
  // Redaction: secrets present in the environment never reach an output or the summary.
  for (const secret of Object.values(SECRETS)) {
    expect(stderr).not.toContain(secret)
    expect(child.stdout()).not.toContain(secret)
    expect(summaryText).not.toContain(secret)
  }
  expect(summaryText).not.toMatch(/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-/i)
  expect(summaryText).not.toMatch(/https?:\/\//)
}

describe.skipIf(isWindows)('real signals (POSIX)', () => {
  it.each(
    (Object.keys(PHASES) as Phase[]).flatMap((phase) =>
      (['SIGINT', 'SIGTERM', 'SIGHUP'] as const).map((signal) => [phase, signal] as const),
    ),
  )(
    '%s interrupted by %s',
    async (phase, signal) => {
      const child = startPosix(phase)
      await child.ready()
      process.kill(child.pid, signal)
      assertInterrupted(child, phase, await child.exited(20_000))
    },
    90_000,
  )
})

describe.skipIf(!isWindows)('real console control events (Windows)', () => {
  function sendConsoleEvent(pid: number, event: 'CtrlC' | 'CtrlBreak'): void {
    // Not awaited: the sender shares the target's console, so Ctrl+Break kills it too and its own
    // status means nothing. It is reaped with the other children after the test.
    const sender = spawn(
      'powershell.exe',
      [
        '-NoProfile',
        '-ExecutionPolicy',
        'Bypass',
        '-File',
        SENDER,
        '-TargetPid',
        String(pid),
        '-Event',
        event,
      ],
      { windowsHide: true, stdio: 'ignore' },
    )
    killers.push(() => {
      if (sender.exitCode === null) sender.kill()
    })
  }

  it.each(Object.keys(PHASES) as Phase[])(
    '%s interrupted by Ctrl+Break (SIGBREAK)',
    async (phase) => {
      const child = await startWindows(phase)
      await child.ready()
      sendConsoleEvent(child.pid, 'CtrlBreak')
      assertInterrupted(child, phase, await child.exited(20_000))
    },
    90_000,
  )

  it('Ctrl+C (SIGINT) is handled in every phase', async (ctx) => {
    for (const phase of Object.keys(PHASES) as Phase[]) {
      const child = await startWindows(phase)
      await child.ready()
      sendConsoleEvent(child.pid, 'CtrlC')
      await sleep(6_000)
      if (alive(child.pid)) {
        child.kill()
        ctx.skip(
          'Ctrl+C is disabled for this process tree (started with CREATE_NEW_PROCESS_GROUP), so ' +
            'SIGINT cannot be delivered from here; the Ctrl+Break tests above exercise the same handler',
        )
        return
      }
      assertInterrupted(child, phase, await child.exited(5_000))
    }
  }, 180_000)
})
